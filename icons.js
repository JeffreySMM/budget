/** @returns {SVGSVGElement | null} the pixel drawing of an icon */
export function pixelIcon(key) {
  if (!isIconKey(key)) return null;
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 10 10');
  svg.setAttribute('shape-rendering', 'crispEdges');
  ICONS[key].forEach((row, y) => [...row].forEach((cell, x) => {
    if (cell === '.') return;
    const pixel = document.createElementNS(SVG_NS, 'rect');
    Object.entries({ x, y, width: 1, height: 1, fill: cell === '#' ? '#000' : DETAILS[key][1] })
      .forEach(([attribute, value]) => pixel.setAttribute(attribute, value));
    svg.append(pixel);
  }));
  return svg;
}
